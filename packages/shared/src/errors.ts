export type ApiErrorCode = (typeof API_ERROR_CODES)[number];

/** One invalid input field. `messages` never contain the submitted value. */
export interface ApiFieldError {
  field: string;
  messages: string[];
}

/** Body of every non-2xx API response. */
export interface ApiErrorBody {
  statusCode: number;
  code: ApiErrorCode;
  message: string;
  /**
   * Present for VALIDATION_ERROR, and for INVENTORY_INSUFFICIENT_STOCK when
   * processing an order (one entry per short line, field `items.<orderItemId>`).
   */
  details?: ApiFieldError[];
}
